/**
 * Pure physics and acoustics calculation module for super-heavy rocket engines.
 * Computes multi-layer exhaust shear, sub-bass rumble, SRB roar, Max-Q aerodynamic
 * buffeting, cockpit structural transmission, speed-of-sound delay, and Doppler shift.
 *
 * SIM LAYER RULE: Pure mathematical functions only. No React, Three.js, or DOM globals.
 */

export const SPEED_OF_SOUND_SEA_LEVEL_MS = 343.2; // 20°C dry air

export interface RocketAcousticsInput {
  throttle: number;             // 0.0 to 1.0 (or up to 1.09 for RS-25 max power)
  altitudeKm: number;           // 0 to 165 km
  dynamicPressureKpa: number;   // 0 to ~38 kPa (Max-Q ~33 kPa)
  machNumber: number;           // 0 to Mach 25+
  srbSeparated: boolean;        // true after booster separation (~45 km)
  coreSeparated: boolean;       // true after MECO (~165 km)
  isCockpit: boolean;           // true in cockpit / cabin camera mode
  cameraDistanceM: number;      // distance from vehicle to camera in meters
  radialVelocityMs?: number;    // velocity component toward (+)/away (-) from camera
}

export interface RocketAcousticsOutput {
  subBassRumbleGain: number;    // Layer 1: 30-80 Hz sub-bass
  exhaustCrackleGain: number;   // Layer 2: 1200-3500 Hz supersonic shear crackle
  srbRoarGain: number;          // Layer 3: 150-800 Hz gritty solid motor roar
  buffetGain: number;           // Layer 4: aerodynamic boundary layer noise
  buffetFreqHz: number;         // resonant center frequency of buffeting
  cabinFilterCutoffHz: number;  // Layer 5: cockpit hull lowpass filter cutoff
  distanceDelaySec: number;     // speed of sound propagation delay
  airAbsorptionCutoffHz: number;// high-frequency atmospheric absorption rolloff
  distanceAttenuation: number; // inverse-square + atmospheric gain factor
  dopplerPitchRatio: number;    // pitch multiplier (1.0 = nominal)
  totalEngineGain: number;      // composite normalized engine bus level
}

/**
 * Computes Layer 1 Sub-Bass Rumble (30-80 Hz).
 * Driven by large-scale turbulent eddies in exhaust plume.
 * Scales with engine throttle and slightly attenuates in near-vacuum.
 */
export function computeSubBassRumble(throttle: number, altitudeKm: number): number {
  if (throttle <= 0.01) return 0;
  // Vacuum attenuation: sub-rumble felt mechanically inside spacecraft even in vacuum
  const atmoRatio = Math.max(0.18, 1 - Math.min(1, altitudeKm / 110));
  return Math.min(1.0, Math.pow(throttle, 0.85) * (0.35 + 0.65 * atmoRatio));
}

/**
 * Computes Layer 2 Supersonic Exhaust Shear Crackle (1200-3500 Hz).
 * Generated by coalescing Mach shock fronts in the supersonic shear layer.
 * Strongly dependent on ambient atmospheric air density to carry acoustic shockwaves.
 */
export function computeExhaustCrackle(
  throttle: number,
  altitudeKm: number,
  machNumber: number
): number {
  if (throttle <= 0.05) return 0;
  // Exponential atmospheric density decay (scale height ~7.5 km)
  const atmoDensity = Math.exp(-altitudeKm / 8.2);
  // Crackle peaks at high power settings when exhaust velocity is supersonic relative to ambient
  const powerFactor = Math.pow(Math.min(1.09, throttle), 1.6);
  // Transonic airspeed adds shear velocity gradient
  const airspeedFactor = 1.0 + Math.min(0.45, machNumber * 0.15);
  return Math.min(1.0, powerFactor * atmoDensity * airspeedFactor);
}

/**
 * Computes Layer 3 Solid Rocket Booster Roar (150-800 Hz).
 * Harsh, gritty acoustic signature from aluminum oxide particle combustion.
 * Active exclusively while SRBs burn prior to booster separation.
 */
export function computeSrbRoar(throttle: number, srbSeparated: boolean): number {
  if (srbSeparated || throttle <= 0.05) return 0;
  // Solid propellant burning rate is nominally flat/steep; delivers ~75% of pad thrust
  return Math.min(1.0, 0.25 + 0.75 * throttle);
}

/**
 * Computes Layer 4 Aerodynamic Buffeting Noise.
 * Boundary layer pressure fluctuations peaking near Maximum Dynamic Pressure (Max-Q).
 */
export function computeAtmosphericBuffet(
  dynamicPressureKpa: number,
  altitudeKm: number
): { gain: number; centerFreqHz: number } {
  // Max-Q typically occurs around 30-36 kPa
  const qRatio = Math.min(1.2, dynamicPressureKpa / 34.0);
  const atmoGate = altitudeKm > 40 ? Math.max(0, 1 - (altitudeKm - 40) / 15) : 1.0;
  const gain = Math.min(1.0, Math.pow(qRatio, 1.4) * atmoGate * 0.95);
  // Resonant buffeting frequency sweeps higher as vehicle accelerates through sound barrier
  const centerFreqHz = Math.min(380, 95 + qRatio * 185);
  return { gain, centerFreqHz };
}

/**
 * Computes Layer 5 Cockpit Hull Transmission Low-pass Filter.
 * Attenuates high airborne frequencies through the spacecraft pressure vessel,
 * leaving low-frequency mechanical vibrations.
 */
export function computeCockpitFilterCutoff(isCockpit: boolean): number {
  return isCockpit ? 380 : 18000;
}

/**
 * Computes Speed of Sound Delay (t = d / c_s).
 * Clamped to prevent unrealistic audio buffer lag in gameplay cameras.
 */
export function computeAcousticDistanceDelay(
  distanceM: number,
  speedOfSoundMs = SPEED_OF_SOUND_SEA_LEVEL_MS
): number {
  const rawDelay = Math.max(0, distanceM) / speedOfSoundMs;
  // Clamp between 0 and 0.85 seconds for responsive gameplay feedback
  return Math.min(0.85, rawDelay);
}

/**
 * Computes Atmospheric High-Frequency Absorption Rolloff.
 * High frequencies attenuate rapidly over distance due to molecular relaxation.
 */
export function computeAirAbsorptionCutoff(distanceM: number): number {
  const dist = Math.max(1, distanceM);
  // Near pad (dist < 30m): full spectrum (18 kHz). Far pad (dist > 500m): rolls off to < 1.8 kHz
  return Math.max(750, 18000 / (1.0 + Math.pow(dist / 95, 0.92)));
}

/**
 * Computes Doppler Frequency Pitch Multiplier.
 * Positive radial velocity indicates moving toward listener; negative indicates moving away.
 */
export function computeDopplerRatio(
  radialVelocityMs = 0,
  speedOfSoundMs = SPEED_OF_SOUND_SEA_LEVEL_MS
): number {
  // Clamp effective velocity to avoid sonic singularity in audio pitch
  const clampedV = Math.max(-speedOfSoundMs * 0.75, Math.min(speedOfSoundMs * 0.75, radialVelocityMs));
  const ratio = speedOfSoundMs / (speedOfSoundMs - clampedV);
  return Math.max(0.4, Math.min(2.5, ratio));
}

/**
 * Master multi-layer acoustic solver synthesizing all 5 layers into coherent telemetry.
 */
export function computeRocketAcoustics(input: RocketAcousticsInput): RocketAcousticsOutput {
  const {
    throttle,
    altitudeKm,
    dynamicPressureKpa,
    machNumber,
    srbSeparated,
    coreSeparated,
    isCockpit,
    cameraDistanceM,
    radialVelocityMs = 0,
  } = input;

  if (coreSeparated && throttle <= 0.01) {
    return {
      subBassRumbleGain: 0,
      exhaustCrackleGain: 0,
      srbRoarGain: 0,
      buffetGain: 0,
      buffetFreqHz: 120,
      cabinFilterCutoffHz: computeCockpitFilterCutoff(isCockpit),
      distanceDelaySec: 0,
      airAbsorptionCutoffHz: 18000,
      distanceAttenuation: 0,
      dopplerPitchRatio: 1.0,
      totalEngineGain: 0,
    };
  }

  const subBass = computeSubBassRumble(throttle, altitudeKm);
  const crackle = computeExhaustCrackle(throttle, altitudeKm, machNumber);
  const srb = computeSrbRoar(throttle, srbSeparated);
  const buffet = computeAtmosphericBuffet(dynamicPressureKpa, altitudeKm);
  const cabinCutoff = computeCockpitFilterCutoff(isCockpit);
  const distanceDelay = computeAcousticDistanceDelay(cameraDistanceM);
  const absorptionCutoff = computeAirAbsorptionCutoff(cameraDistanceM);
  const doppler = computeDopplerRatio(radialVelocityMs);

  // Inverse square distance attenuation with reference distance 35 meters
  const dist = Math.max(10, cameraDistanceM);
  const distAtten = isCockpit
    ? 0.72 // Cockpit volume remains steady regardless of external camera position
    : Math.min(1.0, 35.0 / (35.0 + Math.pow(dist / 35.0, 1.25)));

  // Weighted total engine bus power
  const srbWeight = srbSeparated ? 0 : 0.42;
  const rawSum = subBass * 0.32 + crackle * 0.36 + srb * srbWeight + buffet.gain * 0.18;
  const totalEngineGain = Math.min(1.0, rawSum * distAtten);

  return {
    subBassRumbleGain: Math.round(subBass * 1000) / 1000,
    exhaustCrackleGain: Math.round(crackle * 1000) / 1000,
    srbRoarGain: Math.round(srb * 1000) / 1000,
    buffetGain: Math.round(buffet.gain * 1000) / 1000,
    buffetFreqHz: Math.round(buffet.centerFreqHz),
    cabinFilterCutoffHz: cabinCutoff,
    distanceDelaySec: Math.round(distanceDelay * 1000) / 1000,
    airAbsorptionCutoffHz: Math.round(absorptionCutoff),
    distanceAttenuation: Math.round(distAtten * 1000) / 1000,
    dopplerPitchRatio: Math.round(doppler * 1000) / 1000,
    totalEngineGain: Math.round(totalEngineGain * 1000) / 1000,
  };
}
