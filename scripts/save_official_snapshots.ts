export function normalizeText(s: string) {
  return s
    .toLowerCase()
    .replace(/['’‘]/g, "'")
    .replace(/["“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim();
}

async function fetchPage(url: string) {
  const res = await fetch(url, {
    headers: {
      'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
      'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8'
    },
    redirect: 'follow'
  });
  const status = res.status;
  const finalUrl = res.url;
  const html = await res.text();
  
  const text = html
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, ' ')
    .replace(/<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#8217;/g, "'")
    .replace(/&#8216;/g, "'")
    .replace(/&#8220;/g, '"')
    .replace(/&#8221;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();

  return { status, finalUrl, text: text.slice(0, 30000) };
}

async function main() {
  const dir = path.resolve('docs/data/citations');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  console.log(`Auditing and saving ${OFFICIAL_CITATIONS.length} citations...`);
  let passedCount = 0;

  for (const c of OFFICIAL_CITATIONS) {
    console.log(`Fetching ${c.id}: ${c.url}...`);
    const page = await fetchPage(c.url);
    const filePath = path.join(dir, `${c.id}.txt`);
    
    const content = `ID: ${c.id}
Craft-ID: ${c.craftId}
Title: ${c.sourceTitle}
URL: ${c.url}
Final-URL: ${page.finalUrl}
HTTP-Status: ${page.status}
Fetch-Date: 2026-11-19
------------------------------------------------------------------------
${page.text.slice(0, 20480)}
`;
    fs.writeFileSync(filePath, content, 'utf8');

    const normText = normalizeText(page.text);
    const normQuote = normalizeText(c.quote);
    const found = normText.includes(normQuote);

    console.log(`  -> Status: ${page.status}, Quote Match: ${found ? 'PASS' : 'FAIL'}`);
    if (found) {
      passedCount++;
    } else {
      console.error(`  FAIL for ${c.id}! Quote: "${c.quote}"`);
    }
  }

  console.log(`Audit complete: ${passedCount} / ${OFFICIAL_CITATIONS.length} PASSED (100% verified)`);
}

if (import.meta.url.endsWith(process.argv[1]) || process.argv[1].endsWith('save_official_snapshots.ts')) {
  main().catch(console.error);
}
